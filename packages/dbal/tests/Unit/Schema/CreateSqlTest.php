<?php

declare(strict_types=1);

namespace Prism\Dbal\Tests\Unit\Schema;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Prism\Dbal\Exception\InvalidSchemaException;
use Prism\Dbal\Platform\AbstractPlatform;
use Prism\Dbal\Platform\MariaDbPlatform;
use Prism\Dbal\Platform\MySqlPlatform;
use Prism\Dbal\Platform\PostgreSqlPlatform;
use Prism\Dbal\Platform\SqlitePlatform;
use Prism\Dbal\Schema\Column;
use Prism\Dbal\Schema\ForeignKeyAction;
use Prism\Dbal\Schema\Schema;
use Prism\Dbal\Schema\Sequence;
use Prism\Dbal\Schema\Table;
use Prism\Dbal\Tests\Support\ReferenceSchemas;

/**
 * Instantanés du DDL généré : toute variation du SQL d'une plateforme est volontaire et visible.
 */
final class CreateSqlTest extends TestCase
{
    private static function schema(): Schema
    {
        return new Schema([
            new Table('client', [new Column('id', 'bigint', autoincrement: true), new Column('name', 'string', length: 100)], ['id']),
            new Table('invoice', [
                new Column('id', 'bigint', autoincrement: true),
                new Column('client_id', 'bigint'),
                new Column('total', 'decimal', default: '0.00', precision: 12, scale: 2),
                new Column('paid', 'boolean', default: false),
            ], ['id'])->withIndexOn(['client_id'], name: 'idx_client')->withForeignKeyTo(['client_id'], 'client', ['id'], ForeignKeyAction::Cascade, 'fk_client'),
        ]);
    }

    public function testMySql(): void
    {
        self::assertSame([
            'CREATE TABLE `client` (`id` BIGINT NOT NULL AUTO_INCREMENT, `name` VARCHAR(100) NOT NULL, PRIMARY KEY (`id`))',
            'CREATE TABLE `invoice` (`id` BIGINT NOT NULL AUTO_INCREMENT, `client_id` BIGINT NOT NULL, `total` DECIMAL(12, 2) NOT NULL DEFAULT \'0.00\', `paid` TINYINT(1) NOT NULL DEFAULT 0, PRIMARY KEY (`id`))',
            'CREATE INDEX `idx_client` ON `invoice` (`client_id`)',
            'ALTER TABLE `invoice` ADD CONSTRAINT `fk_client` FOREIGN KEY (`client_id`) REFERENCES `client` (`id`) ON DELETE CASCADE',
        ], new MySqlPlatform('8.4')->getCreateSchemaSql(self::schema()));
    }

    public function testPostgreSql(): void
    {
        self::assertSame([
            'CREATE TABLE "client" ("id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "name" VARCHAR(100) NOT NULL, PRIMARY KEY ("id"))',
            'CREATE TABLE "invoice" ("id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY, "client_id" BIGINT NOT NULL, "total" NUMERIC(12, 2) NOT NULL DEFAULT \'0.00\', "paid" BOOLEAN NOT NULL DEFAULT FALSE, PRIMARY KEY ("id"))',
            'CREATE INDEX "idx_client" ON "invoice" ("client_id")',
            'ALTER TABLE "invoice" ADD CONSTRAINT "fk_client" FOREIGN KEY ("client_id") REFERENCES "client" ("id") ON DELETE CASCADE',
        ], new PostgreSqlPlatform('16')->getCreateSchemaSql(self::schema()));
    }

    // SQLite : clé étrangère dans le CREATE TABLE, INTEGER PRIMARY KEY pour l'auto-incrément
    public function testSqlite(): void
    {
        self::assertSame([
            'CREATE TABLE "client" ("id" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT, "name" VARCHAR(100) NOT NULL)',
            'CREATE TABLE "invoice" ("id" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT, "client_id" BIGINT NOT NULL, "total" NUMERIC(12, 2) NOT NULL DEFAULT \'0.00\', "paid" BOOLEAN NOT NULL DEFAULT 0, CONSTRAINT "fk_client" FOREIGN KEY ("client_id") REFERENCES "client" ("id") ON DELETE CASCADE)',
            'CREATE INDEX "idx_client" ON "invoice" ("client_id")',
        ], new SqlitePlatform('3.46')->getCreateSchemaSql(self::schema()));
    }

    /**
     * @return iterable<string, array{AbstractPlatform, string}>
     */
    public static function everyTypeDeclarations(): iterable
    {
        yield 'MySQL' => [new MySqlPlatform('8.4'), 'INT|VARCHAR(120)|VARCHAR(255)|LONGTEXT|SMALLINT|BIGINT|TINYINT(1)|DECIMAL(12, 2)|DOUBLE|DATETIME|DATE|TIME|JSON|CHAR(36)|VARBINARY(64)|LONGBLOB'];
        yield 'MariaDB' => [new MariaDbPlatform('11.8'), 'INT|VARCHAR(120)|VARCHAR(255)|LONGTEXT|SMALLINT|BIGINT|TINYINT(1)|DECIMAL(12, 2)|DOUBLE|DATETIME|DATE|TIME|JSON|UUID|VARBINARY(64)|LONGBLOB'];
        yield 'PostgreSQL' => [new PostgreSqlPlatform('16'), 'INTEGER|VARCHAR(120)|VARCHAR(255)|TEXT|SMALLINT|BIGINT|BOOLEAN|NUMERIC(12, 2)|DOUBLE PRECISION|TIMESTAMP(0) WITHOUT TIME ZONE|DATE|TIME(0) WITHOUT TIME ZONE|JSONB|UUID|BYTEA|BYTEA'];
        yield 'SQLite' => [new SqlitePlatform('3.46'), 'INTEGER|VARCHAR(120)|VARCHAR(255)|TEXT|SMALLINT|BIGINT|BOOLEAN|NUMERIC(12, 2)|DOUBLE PRECISION|DATETIME|DATE|TIME|JSON_TEXT|CHAR(36)|BLOB|BLOB'];
    }

    #[DataProvider('everyTypeDeclarations')]
    public function testTypeDeclarations(AbstractPlatform $platform, string $expected): void
    {
        $table = ReferenceSchemas::everyType();
        $declarations = array_map(
            static fn (Column $c): string => (string) preg_replace('/^\S+ (.+?) (NOT )?NULL$/', '$1', $platform->getColumnDeclarationSql($table, $c)),
            $table->getColumns(),
        );

        self::assertSame($expected, implode('|', $declarations));
    }

    public function testDefaultValuesAreRenderedAsLiterals(): void
    {
        $table = new Table('t', [new Column('a', 'string', default: "O'Reilly \\ co"), new Column('b', 'float', default: 0.1), new Column('c', 'integer', default: -5)]);

        self::assertSame("`a` VARCHAR(255) NOT NULL DEFAULT 'O''Reilly \\\\ co'", new MySqlPlatform('8.4')->getColumnDeclarationSql($table, $table->getColumn('a')));
        self::assertSame("\"a\" VARCHAR(255) NOT NULL DEFAULT 'O''Reilly \\ co'", new PostgreSqlPlatform('16')->getColumnDeclarationSql($table, $table->getColumn('a')));
        self::assertSame('"b" DOUBLE PRECISION NOT NULL DEFAULT 0.1', new PostgreSqlPlatform('16')->getColumnDeclarationSql($table, $table->getColumn('b')));
        self::assertSame('"c" INTEGER NOT NULL DEFAULT -5', new SqlitePlatform('3.46')->getColumnDeclarationSql($table, $table->getColumn('c')));
    }

    public function testDropStatements(): void
    {
        self::assertSame('DROP INDEX `i` ON `t`', new MySqlPlatform('8.4')->getDropIndexSql('t', 'i'));
        self::assertSame('DROP INDEX "i"', new PostgreSqlPlatform('16')->getDropIndexSql('t', 'i'));
        self::assertSame('ALTER TABLE `t` DROP FOREIGN KEY `f`', new MariaDbPlatform('11.8')->getDropForeignKeySql('t', 'f'));
        self::assertSame('ALTER TABLE "t" DROP CONSTRAINT "f"', new PostgreSqlPlatform('16')->getDropForeignKeySql('t', 'f'));
        self::assertSame('DROP TABLE "order"', new SqlitePlatform('3.46')->getDropTableSql('order'));
    }

    public function testSequences(): void
    {
        $sequence = new Sequence('invoice_seq', 1000, 10);

        self::assertSame('CREATE SEQUENCE "invoice_seq" START WITH 1000 INCREMENT BY 10', new PostgreSqlPlatform('16')->getCreateSequenceSql($sequence));
        self::assertSame('CREATE SEQUENCE `invoice_seq` START WITH 1000 INCREMENT BY 10', new MariaDbPlatform('11.8')->getCreateSequenceSql($sequence));
        self::assertSame('DROP SEQUENCE "invoice_seq"', new PostgreSqlPlatform('16')->getDropSequenceSql('invoice_seq'));
        self::assertFalse(new MySqlPlatform('8.4')->supportsSequences());
        self::assertFalse(new SqlitePlatform('3.46')->supportsSequences());
    }

    /**
     * @return iterable<string, array{\Closure(): mixed, string}>
     */
    public static function unsupported(): iterable
    {
        yield 'sequence on MySQL' => [static fn (): string => new MySqlPlatform('8.4')->getCreateSequenceSql(new Sequence('s')), 'MySQL does not support sequences'];
        yield 'drop sequence on SQLite' => [static fn (): string => new SqlitePlatform('3.46')->getDropSequenceSql('s'), 'SQLite does not support sequences'];
        yield 'alter foreign key on SQLite' => [static fn (): string => new SqlitePlatform('3.46')->getDropForeignKeySql('t', 'f'), 'the table must be rebuilt'];
        yield 'unknown type' => [static fn (): string => new PostgreSqlPlatform('16')->getCreateTableSql(new Table('t', [new Column('geo', 'geometry')])), 'PostgreSQL cannot declare column "t.geo" of type "geometry"'];
    }

    /**
     * @param \Closure(): mixed $build
     */
    #[DataProvider('unsupported')]
    public function testUnsupportedFeaturesAreRefused(\Closure $build, string $message): void
    {
        $this->expectException(InvalidSchemaException::class);
        $this->expectExceptionMessage($message);

        $build();
    }
}
